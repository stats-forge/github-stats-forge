#!/usr/bin/env node
/**
 * @file Writes the theme reference page.
 *
 * The table is the theme table — a page listing the themes by hand would be wrong within a release.
 * Run it after touching `packages/core/src/themes/index.ts`; `--check` is what CI runs.
 *
 * The output goes through oxfmt, as the GraphQL generator's does, so `pnpm format` leaves it alone
 * and `--check` compares against what the formatter would have written anyway.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import { defineConfig } from '@marcalexiei/oxfmt-config';
import { themes } from '@stats-forge/github-stats-forge-core/themes';
import { format } from 'oxfmt';

import { SAMPLE_THEMES, THEMES_DIR } from '../src/constants.ts';

const PAGE = fileURLToPath(
  new URL('../src/content/docs/docs/customization/themes.md', import.meta.url),
);

/**
 * A swatch and the value behind it, as one cell.
 *
 * @returns The cell's markdown.
 */
const swatch = (value: string): string =>
  `<span class="theme-swatch" style="background:#${value}"></span> \`${value}\``;

/** @returns The heat's cell: one wide swatch of the gradient, then its stops. */
const heatSwatch = (heat: ReadonlyArray<string>): string => {
  const stops = heat.map((stop) => `#${stop}`).join(', ');
  const values = heat.map((stop) => `\`${stop}\``).join(' ');
  return `<span class="theme-swatch theme-swatch--wide" style="background:linear-gradient(90deg, ${stops})"></span> ${values}`;
};

/**
 * @returns The whole page.
 */
const render = (): string => {
  const rows = Object.entries(themes).map(
    ([name, theme]) =>
      `| \`${name}\` | ${heatSwatch(theme.heat)} | ${swatch(theme.text_color)} | ${swatch(theme.bg_color)} |`,
  );

  return [
    '---',
    'title: Themes',
    `description: The ${String(rows.length)} built-in themes, and the colors each one sets.`,
    '---',
    '',
    '<!-- Generated by scripts/generate-themes-page.ts. Edit the theme table in packages/core instead. -->',
    '',
    'Each theme is one look, and its name says the background it was drawn for. Name one and the',
    "card always wears it; name two, `light,dark`, and the card switches with the viewer's setting.",
    'With no theme, a card wears `ember_light,ember_dark`.',
    '',
    '```text',
    '?username=octocat&theme=cobalt_dark',
    '?username=octocat&theme=brass_light,magma_dark',
    '```',
    '',
    'A theme sets every color on the card. The heat is a gradient: its brightest stop to its deepest',
    'paints the title, the band and trail behind it, the rank ring and the corner glow.',
    '',
    'An unknown name is an error, `Incorrect theme input`, rather than a card in the wrong colors.',
    '',
    '## A few of them, drawn',
    '',
    'The same stats card, rendered by the CLI in a few of the themes below. A pair follows your',
    "browser's color scheme, so switch it to see the other half.",
    '',
    ...Object.entries(SAMPLE_THEMES).flatMap(([file, theme]) => [
      `### \`${theme}\``,
      '',
      `![The stats card in ${theme}](/${THEMES_DIR}/${file}.svg)`,
      '',
    ]),
    `## The ${String(rows.length)} built-in themes`,
    '',
    '| Theme | Heat | Text | Background |',
    '| ----- | ---- | ---- | ---------- |',
    ...rows,
    '',
  ].join('\n');
};

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
const formatted = await format(PAGE, render(), defineConfig());
const page = formatted.code;

if (values.check) {
  const current = await readFile(PAGE, 'utf8').catch(() => '');
  if (current !== page) {
    process.stderr.write(
      'themes.md is out of date. Run `pnpm --filter ./apps/docs run generate-themes-page`.\n',
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(PAGE, page, 'utf8');
  process.stdout.write(`Wrote ${PAGE}\n`);
}
