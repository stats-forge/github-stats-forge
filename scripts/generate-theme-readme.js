import fs from "fs";
import path from "path";

import { format, resolveConfig } from "prettier";

import { themes } from "../packages/core/src/themes/index.ts";

// The list lives with the themes it documents.
const TARGET_FILE = path.join(
  import.meta.dirname,
  "../packages/core/src/themes/README.md",
);
// Absolute, because this snippet is meant to be pasted into someone else's README.
const INSTANCE_URL =
  process.env.PUBLIC_INSTANCE_URL ?? "https://your-instance.example.com";
const REPO_CARD_LINKS_FLAG = "<!-- REPO_CARD_LINKS -->";
const STAT_CARD_LINKS_FLAG = "<!-- STATS_CARD_LINKS -->";

const STAT_CARD_TABLE_FLAG = "<!-- STATS_CARD_TABLE -->";
const REPO_CARD_TABLE_FLAG = "<!-- REPO_CARD_TABLE -->";

const THEME_TEMPLATE = `## Available Themes

<!-- DO NOT EDIT THIS FILE DIRECTLY -->

With inbuilt themes, you can customize the look of the card without doing any manual customization.

Use \`?theme=THEME_NAME\` parameter like so:

\`\`\`md
![Anurag's GitHub stats](${INSTANCE_URL}/api/stats?username=anuraghazra&theme=dark&show_icons=true)
\`\`\`

## Stats

> These themes work with all five of our cards: Stats Card, Repo Card, Gist Card, Top Languages Card, and WakaTime Card.

| | | |
| :--: | :--: | :--: |
${STAT_CARD_TABLE_FLAG}

## Repo Card

> These themes work with all five of our cards: Stats Card, Repo Card, Gist Card, Top Languages Card, and WakaTime Card.

| | | |
| :--: | :--: | :--: |
${REPO_CARD_TABLE_FLAG}

${STAT_CARD_LINKS_FLAG}

${REPO_CARD_LINKS_FLAG}
`;

// Absolute like the snippet above: this file is read on npm and on GitHub, where
// a root-relative card URL resolves against the wrong host.
const createRepoMdLink = (theme) => {
  return `\n[${theme}_repo]: ${INSTANCE_URL}/api/pin?username=anuraghazra&repo=github-readme-stats&cache_seconds=86400&theme=${theme}`;
};
const createStatMdLink = (theme) => {
  return `\n[${theme}]: ${INSTANCE_URL}/api/stats?username=anuraghazra&show_icons=true&hide=contribs,prs&cache_seconds=86400&theme=${theme}`;
};

const generateLinks = (fn) => {
  return Object.keys(themes)
    .map((name) => fn(name))
    .join("");
};

const createTableItem = ({ link, label, isRepoCard }) => {
  if (!link || !label) {
    return "";
  }
  return `\`${label}\` ![${link}][${link}${isRepoCard ? "_repo" : ""}]`;
};

const allThemeNames = Object.keys(themes);

// Some themes come in pairs: `X_repocard` for the repo and gist cards, `X` for
// the stats, top languages and WakaTime cards. Each table lists only its own
// variant.
//
// Keep in sync with the theme lists shipped by consumers,
// which splits the picker by the same rule.
const repoCardThemes = allThemeNames.filter(
  (name) => !allThemeNames.includes(`${name}_repocard`),
);

const nonRepoCardThemes = allThemeNames.filter(
  (name) => !name.endsWith("_repocard"),
);

const generateTable = ({ isRepoCard }) => {
  const rows = [];
  const themesFiltered = isRepoCard ? repoCardThemes : nonRepoCardThemes;

  for (let i = 0; i < themesFiltered.length; i += 3) {
    const one = themesFiltered[i];
    const two = themesFiltered[i + 1];
    const three = themesFiltered[i + 2];

    let tableItem1 = createTableItem({ link: one, label: one, isRepoCard });
    let tableItem2 = createTableItem({ link: two, label: two, isRepoCard });
    let tableItem3 = createTableItem({ link: three, label: three, isRepoCard });

    rows.push(`| ${tableItem1} | ${tableItem2} | ${tableItem3} |`);
  }

  return rows.join("\n");
};

const buildReadme = () => {
  return THEME_TEMPLATE.split("\n")
    .map((line) => {
      if (line.includes(REPO_CARD_LINKS_FLAG)) {
        return generateLinks(createRepoMdLink);
      }
      if (line.includes(STAT_CARD_LINKS_FLAG)) {
        return generateLinks(createStatMdLink);
      }
      if (line.includes(REPO_CARD_TABLE_FLAG)) {
        return generateTable({ isRepoCard: true });
      }
      if (line.includes(STAT_CARD_TABLE_FLAG)) {
        return generateTable({ isRepoCard: false });
      }
      return line;
    })
    .join("\n");
};

const prettierConfig = await resolveConfig(TARGET_FILE);

fs.writeFileSync(
  TARGET_FILE,
  await format(buildReadme(), {
    ...prettierConfig,
    parser: "markdown",
  }),
);
